#include <Editor/Manager/EditorWindowRegistry.h>

#if ENGINE_EDITOR_ONLY

#include <imgui.h>

#include <Development/EditorLogManager.h>
#include <Editor/Manager/EditorMenuRegistry.h>
#include <Editor/Manager/EditorSettings.h>

namespace PigeonEngine
{
	namespace
	{
		TArray<FEditorWindowDesc>	Windows;
		TMap<EString, INT32>		WindowLookup;

		BOOL32 IsValidWindowId(const EString& InId)
		{
			if (InId.Length() == 0u)
			{
				return FALSE;
			}
			for (UINT32 Index = 0u; Index < InId.Length(); Index++)
			{
				const CHAR Char = InId[Index];
				// The id is appended to "Panels." and used as a menu/lookup key; spaces
				// and dots would turn it into a different settings path.
				if ((Char == '.') || (Char == ' ') || (Char == '\t'))
				{
					return FALSE;
				}
			}
			return TRUE;
		}

		FEditorWindowDesc* FindWindow(const EString& InId)
		{
			const INT32* FoundIndex = WindowLookup.FindValueAsPtr(InId);
			return FoundIndex ? &Windows[*FoundIndex] : nullptr;
		}

		void SetWindowVisibility(FEditorWindowDesc& InWindow, const BOOL32& bInVisible)
		{
			if (InWindow.bVisible == bInVisible)
			{
				return;
			}
			InWindow.bVisible = bInVisible;
			EEditorSettings::SetPanelVisible(InWindow.Id, bInVisible);
		}
	}

	namespace EEditorWindowRegistry
	{
		void RegisterWindow(const FEditorWindowDesc& InWindow)
		{
			if ((InWindow.Title.Length() == 0u) || (!InWindow.Draw))
			{
				PE_LOG_ERROR(EString("EditorWindowRegistry: a window needs a title and a draw callback."));
				return;
			}
			if (IsValidWindowId(InWindow.Id) == FALSE)
			{
				PE_LOG_ERROR(EString("EditorWindowRegistry: invalid window id: ") + InWindow.Id);
				return;
			}
			if (FindWindow(InWindow.Id))
			{
				PE_LOG_ERROR(EString("EditorWindowRegistry: duplicate window id: ") + InWindow.Id);
				return;
			}

			FEditorWindowDesc Entry = InWindow;
			Entry.bVisible = Entry.bDefaultVisible;
			WindowLookup.Add(Entry.Id, Windows.Num<INT32>());
			Windows.Add(Entry);

			// Declared before EEditorSettings::Initialize() loads the files, so the tracked
			// default and the user override both apply to this key.
			EEditorSettings::RegisterPanelVisibility(Entry.Id, Entry.bDefaultVisible);

			// The Window menu is generated by the same path-based menu registry as File,
			// Edit and Build. The toggle reads and writes this window's visibility.
			EString MenuPath = Entry.MenuPath;
			if (MenuPath.Length() == 0u)
			{
				MenuPath = EString("Window/");
				MenuPath += Entry.Title;
			}
			const EString WindowId = Entry.Id;
			EEditorMenuRegistry::RegisterItem({
				MenuPath,
				[WindowId]() -> void
				{
					FEditorWindowDesc* Window = FindWindow(WindowId);
					if (Window)
					{
						SetWindowVisibility(*Window, (Window->bVisible != FALSE) ? FALSE : TRUE);
					}
				},
				EString(),
				nullptr,
				nullptr,
				nullptr,
				[WindowId]() -> BOOL32
				{
					const FEditorWindowDesc* Window = FindWindow(WindowId);
					return ((Window) && (Window->bVisible != FALSE)) ? TRUE : FALSE;
				}
			});
		}

		void Initialize()
		{
			for (INT32 Index = 0, WindowNum = Windows.Num<INT32>(); Index < WindowNum; Index++)
			{
				FEditorWindowDesc& Window = Windows[Index];
				Window.bVisible = EEditorSettings::IsPanelVisible(Window.Id);
			}
		}

		void DrawWindow(const EString& InId)
		{
			FEditorWindowDesc* Window = FindWindow(InId);
			if (!Window || (Window->bVisible == FALSE) || (!Window->Draw))
			{
				return;
			}

			if ((Window->DefaultSize.x > 0.0f) && (Window->DefaultSize.y > 0.0f))
			{
				ImGui::SetNextWindowSize(Window->DefaultSize, ImGuiCond_FirstUseEver);
			}

			BOOL32 bOpen = TRUE;
			if (ImGui::Begin(*Window->Title, &bOpen))
			{
				Window->Draw();
			}
			ImGui::End();

			SetWindowVisibility(*Window, bOpen);
		}

		void Clear()
		{
			Windows.Empty();
			WindowLookup.Empty();
		}
	}
}

#endif
